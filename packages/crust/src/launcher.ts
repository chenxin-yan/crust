import type { DistributionTarget } from "./distribute.ts";

/** Node.js the launcher needs for `process.execve`: the same floor as every Crust package. */
export const LAUNCHER_NODE_RANGE = ">=24";

/** Platform binary filename: `<command>-<target>`, `.exe` on Windows. */
export function binaryFilename(command: string, target: DistributionTarget): string {
	return `${command}-${target.target}${target.os === "win32" ? ".exe" : ""}`;
}

export function generateLauncher(command: string, targets: readonly DistributionTarget[]): string {
	const targetMap = Object.fromEntries(
		targets.map((target) => [
			target.platformKey,
			{
				packagePathSegment: target.packagePathSegment,
				packageName: target.packageName,
				targetAlias: target.targetAlias,
				binaryFilename: binaryFilename(command, target),
			},
		]),
	);
	const supportedPlatforms = targets.map((target) => target.targetAlias).join(", ");

	// The command name is validated by the build planner and embedded as a JSON
	// string literal, never spliced into code.
	return `#!/usr/bin/env node
// Auto-generated by crust build -- do not edit
const NAME = ${JSON.stringify(command)};
if (typeof process.getBuiltinModule !== "function" ||
	(process.platform !== "win32" && typeof process.execve !== "function")) {
	console.error("[" + NAME + "] Requires Node.js ${LAUNCHER_NODE_RANGE} (found " + process.version + ").");
	process.exit(1);
}

// Builtins come from process.getBuiltinModule (cheaper than imports) and never from
// node:process: importing it touches stdio, which leaves the shared terminal and pipes
// non-blocking for the binary after execve.
const { chmodSync, closeSync, existsSync, openSync, readSync } = process.getBuiltinModule("node:fs");
const { resolve } = process.getBuiltinModule("node:path");

const PLATFORMS = ${JSON.stringify(targetMap, null, "\t")};
const dir = import.meta.dirname;

function isMusl() {
	// The first 2 KB of Node's ELF image hold its interpreter path (detect-libc reads the same
	// span), which names its libc without the milliseconds a diagnostic report costs on every start.
	try {
		const fd = openSync("/proc/self/exe", "r");
		const head = Buffer.alloc(2048);
		const interpreter = head.toString("latin1", 0, readSync(fd, head, 0, head.length, 0));
		closeSync(fd);
		if (interpreter.includes("/ld-musl-")) return true;
		if (interpreter.includes("/ld-linux-")) return false;
	} catch {}
	// Same check as Bun's own npm installer: glibc reports its version, musl does not.
	try {
		const report = process.report?.getReport();
		if (report?.header) return report.header.glibcVersionRuntime === undefined;
	} catch {}
	return existsSync("/etc/alpine-release");
}

const platformKey =
	\`\${process.platform}-\${process.arch}\` + (process.platform === "linux" && isMusl() ? "-musl" : "");
const target = PLATFORMS[platformKey];

if (!target) {
\tconsole.error("[" + NAME + "] Unsupported platform: " + platformKey);
\tconsole.error("[" + NAME + "] Supported platforms: ${supportedPlatforms}");
\tprocess.exit(1);
}

const candidates = [
\t// Hoisted install: the platform package beside this one in node_modules.
\tresolve(dir, "..", "..", target.packagePathSegment, "bin", target.binaryFilename),
\t// Nested install: the platform package under this package's node_modules.
\tresolve(dir, "..", "node_modules", target.packageName, "bin", target.binaryFilename),
\t// In place: the .crust/ tree crust build staged, before any install.
\tresolve(dir, "..", "..", target.targetAlias, "bin", target.binaryFilename),
];
const binPath = candidates.find((candidate) => existsSync(candidate));

if (!binPath) {
\tconsole.error("[" + NAME + "] Missing platform package for " + platformKey);
\tconsole.error("[" + NAME + "] Tried:");
\tfor (const candidate of candidates) console.error("  " + candidate);
\tconsole.error(
\t\t"[" + NAME + "] Reinstall dependencies on this platform and ensure optional dependencies are enabled.",
\t);
\tprocess.exit(1);
}

if (process.platform === "win32") {
\tlaunchWindows(binPath);
} else {
\ttry {
\t\tchmodSync(binPath, 0o755);
\t} catch {
\t\t// Ignore permission adjustment failures and let execve surface real errors.
\t}
\t// Become the binary: one process, so signals and exit status reach it with no relay.
\t// Node ignores SIGPIPE and SIGXFSZ, and ignored signals survive execve; handled ones reset.
\tprocess.on("SIGPIPE", () => {});
\tprocess.on("SIGXFSZ", () => {});
\t// Early execve versions (e.g. Node 24.0.0) default to an empty environment.
\tprocess.execve(binPath, [binPath, ...process.argv.slice(2)], process.env);
}

// Windows has no execve. Its console delivers Ctrl-C to the binary directly, and
// child.kill("SIGINT") would hard-terminate it, so SIGINT is never forwarded.
function launchWindows(binPath) {
\tconst { spawn } = process.getBuiltinModule("node:child_process");
\tconst child = spawn(binPath, process.argv.slice(2), { stdio: "inherit" });
\tconst forward = (signal) => child.kill(signal);
\tconst ignore = () => {};
\tprocess.on("SIGINT", ignore);
\tprocess.on("SIGTERM", forward);
\tprocess.on("SIGHUP", forward);
\tchild.on("error", (error) => {
\t\tconsole.error("[" + NAME + "] Failed to launch binary: " + error.message);
\t\tprocess.exit(1);
\t});
\tchild.on("exit", (code, signal) => {
\t\tprocess.off("SIGINT", ignore);
\t\tprocess.off("SIGTERM", forward);
\t\tprocess.off("SIGHUP", forward);
\t\tif (signal) {
\t\t\ttry {
\t\t\t\tprocess.kill(process.pid, signal);
\t\t\t} catch {
\t\t\t\tprocess.exit(1);
\t\t\t}
\t\t\treturn;
\t\t}
\t\tprocess.exit(code ?? 0);
\t});
}
`;
}
