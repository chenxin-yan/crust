import { randomBytes } from "node:crypto";
import { chmod, readFile, realpath, rm, writeFile } from "node:fs/promises";
import { isAbsolute, join, resolve } from "node:path";
import { pathToFileURL } from "node:url";

import { runProcess } from "@crustjs/utils/process";

import {
	type BuildRunner,
	bunCompileTarget,
	processOutput,
	resolveBunBuildRunner,
} from "./compilers.ts";
import type { BunTarget } from "./targets.ts";

export function toBunEnvFileArgs(envFiles: readonly string[]): string[] {
	return envFiles.flatMap((envFile) => ["--env-file", envFile]);
}

/**
 * Module source the generated driver imports for a `crust.bunPlugins` specifier.
 *
 * Paths become file URLs resolved against the project; bare specifiers are
 * imported as written so they resolve from the project's own node_modules.
 */
export function resolveBunPluginSource(specifier: string, cwd: string): string {
	return specifier.startsWith(".") || isAbsolute(specifier)
		? pathToFileURL(resolve(cwd, specifier)).href
		: specifier;
}

/**
 * Marks every Bun/Node bundle crust produces so `resolveArtifactDir` (core)
 * can tell a staged bundle from source at runtime. Not a `PUBLIC_*` variable:
 * it is internal to crust, never user-set.
 */
const CRUST_BUILD_DEFINE = { "process.env.CRUST_INTERNAL_BUILD": '"1"' } as const;
// The value keeps its quotes so bun inlines a string literal, not a number.
const CRUST_BUILD_DEFINE_ARG = 'process.env.CRUST_INTERNAL_BUILD="1"';

type BunPluginDriverBuild = {
	entrypoints: [string];
	minify: boolean;
	env: "PUBLIC_*";
} & (
	| {
			target: "bun";
			compile: { target: string; outfile: string; autoloadBunfig: false };
			bytecode?: true;
			format?: "esm";
	  }
	| { target: "bun" | "node"; format: "esm"; external: readonly string[] }
);

export type BunPluginDriverOptions = {
	plugins: Array<{ specifier: string; source: string }>;
	build: BunPluginDriverBuild;
	outfile: string;
	/** Module paths whose leading shebang line is blanked on load. */
	stripShebang?: string[];
};

/**
 * Script that runs `Bun.build` with the project's bundler plugins.
 *
 * `bun build` has no plugin flag, so plugins are loaded by a generated script
 * placed in the project root (project module resolution) and run with the
 * same runner as the CLI path. Every value is embedded via JSON.stringify.
 */
export function createBunPluginDriverScript(options: BunPluginDriverOptions): string {
	return `// Generated by crust build for crust.bunPlugins; deleted when the build finishes.
const options = ${JSON.stringify(options)};
const plugins = [];
for (const { specifier, source } of options.plugins) {
	let plugin;
	try {
		plugin = (await import(source)).default;
	} catch (error) {
		// Bun names this (soon deleted) driver as the importer; the project root is the useful location.
		const message = (error instanceof Error ? error.message : String(error)).replace(\` imported from \${import.meta.path}\`, "");
		console.error(\`crust.bunPlugins entry \${specifier} could not be imported from \${process.cwd()}: \${message}\`);
		process.exit(1);
	}
	if (typeof plugin !== "object" || plugin === null || typeof plugin.name !== "string" || typeof plugin.setup !== "function") {
		console.error(\`crust.bunPlugins entry \${specifier} must default-export a Bun bundler plugin ({ name, setup }). Wrap a plugin factory in a module that default-exports the created plugin.\`);
		process.exit(1);
	}
	plugins.push(plugin);
}
if (options.stripShebang) {
	// Last, so a project plugin's onLoad for the entry still wins. The emptied line keeps line numbers.
	plugins.push({ name: "crust-strip-shebang", setup(build) {
		build.onLoad({ filter: new RegExp(\`^(?:\${options.stripShebang.map(RegExp.escape).join("|")})$\`) }, async ({ path, loader }) => ({ contents: (await Bun.file(path).text()).replace(/^#![^\\n]*/, ""), loader }));
	} });
}
const result = await Bun.build({ ...options.build, define: ${JSON.stringify(CRUST_BUILD_DEFINE)}, plugins, throw: false });
if (!result.success) {
	for (const log of result.logs) console.error(log);
	process.exit(1);
}
if (!options.build.compile) {
	if (result.outputs.length !== 1) {
		// Same refusal as \`bun build --outfile\`: a file-type asset import yields entry + asset.
		console.error("error: cannot write multiple output files without an output directory");
		process.exit(1);
	}
	await Bun.write(options.outfile, result.outputs[0]);
}
`;
}

/** The build settings every Bun bundling step reads; a build plan satisfies it. */
export type BundleSettings = {
	cwd: string;
	minify: boolean;
	/** Env files whose `PUBLIC_*` values are inlined. */
	envFiles: readonly string[];
	/**
	 * Precompile Bun standalone executables to bytecode (`--bytecode`). Bun embeds
	 * it with its own runtime, so it always matches; Node cannot read it.
	 */
	bytecode?: boolean;
	/** Bun bundler plugin specifiers; when present the build runs through the generated `Bun.build` driver. */
	bunPlugins: readonly string[];
	/** Package names left as bare imports (`crust.external`); runtime packages only. */
	external: readonly string[];
};

async function runBunPluginDriver(
	build: BunPluginDriverBuild,
	outfilePath: string,
	{ cwd, envFiles, bunPlugins }: BundleSettings,
	runner: BuildRunner,
	stripShebang?: string[],
): Promise<void> {
	const driverPath = join(cwd, `.crust-build-${randomBytes(6).toString("hex")}.ts`);
	await writeFile(
		driverPath,
		createBunPluginDriverScript({
			plugins: bunPlugins.map((specifier) => ({
				specifier,
				source: resolveBunPluginSource(specifier, cwd),
			})),
			build,
			outfile: outfilePath,
			stripShebang,
		}),
	);
	try {
		// The runtime loads env files before the script runs, so `env: "PUBLIC_*"`
		// inlines the same values as the CLI path's --env-file/--env flags.
		await runBuildProcess(runner, [...toBunEnvFileArgs(envFiles), driverPath], outfilePath, cwd);
	} finally {
		await rm(driverPath, { force: true });
	}
}

/**
 * Compile a single entry file to a standalone executable.
 *
 * Uses `bun build --compile` as a subprocess so the standalone compiler runs
 * in Bun's CLI process rather than inside the current Crust runtime.
 * This avoids in-process compiler issues seen on some host/target
 * combinations while still supporting env-file loading natively.
 *
 * @param entryPath - Absolute path to the entry file
 * @param outfilePath - Absolute path to the output binary
 * @param target - Bun compile target
 * @param runner - The selected Bun compiler (`resolveBinaryCompiler`)
 * @throws {Error} If the build fails
 */
export async function execBuild(
	entryPath: string,
	outfilePath: string,
	target: BunTarget,
	settings: BundleSettings,
	runner: BuildRunner = resolveBunBuildRunner(),
): Promise<void> {
	const compileTarget = bunCompileTarget(target, runner);
	if (settings.bunPlugins.length > 0) {
		await runBunPluginDriver(
			{
				entrypoints: [entryPath],
				minify: settings.minify,
				env: "PUBLIC_*",
				target: "bun",
				compile: {
					target: compileTarget,
					outfile: outfilePath,
					autoloadBunfig: false,
				},
				// Bytecode defaults to CommonJS output, which rejects top-level await in entry files.
				...(settings.bytecode ? { bytecode: true, format: "esm" } : {}),
			},
			outfilePath,
			settings,
			runner,
		);
		return;
	}
	const args = createBunCompileArgs(
		entryPath,
		outfilePath,
		settings.minify,
		compileTarget,
		settings.envFiles,
		settings.bytecode,
	);
	await runBuildProcess(runner, args, outfilePath, settings.cwd);
}

export function createBunCompileArgs(
	entryPath: string,
	outfilePath: string,
	minify: boolean,
	target: string,
	envFiles: readonly string[] = [],
	bytecode = false,
): string[] {
	return [
		"build",
		"--compile",
		// A standalone otherwise runs the bunfig.toml of whatever directory it is
		// started in, so an unresolvable consumer `preload` would kill it before
		// user code. `.env` autoloading is intentionally left on.
		"--no-compile-autoload-bunfig",
		...toBunEnvFileArgs(envFiles),
		"--env=PUBLIC_*",
		"--define",
		CRUST_BUILD_DEFINE_ARG,
		"--outfile",
		outfilePath,
		...(minify ? ["--minify"] : []),
		// Bytecode defaults to CommonJS output, which rejects top-level await in entry files.
		...(bytecode ? ["--bytecode", "--format=esm"] : []),
		"--target",
		target,
		entryPath,
	];
}

/** Runs one compiler step; returns its output, which a successful step may still print (warnings). */
export async function runBuildProcess(
	runner: BuildRunner,
	args: readonly string[],
	outfilePath: string,
	cwd: string,
): Promise<string> {
	const result = await runProcess(runner.command, args, {
		env: runner.env,
		cwd,
		stdio: "collect",
	});
	const output = processOutput(result);
	if (result.exitCode !== 0) {
		throw new Error(`Build failed for ${outfilePath}${output ? `:\n${output}` : ""}`);
	}
	return output;
}

/**
 * Bundle a runtime package entry as ESM behind `#!/usr/bin/env <target>`: for
 * Node, or Bun-targeted so the installed bin launches with Bun rather than Node.
 */
export async function execScriptBuild(
	target: "bun" | "node",
	entryPath: string,
	outfilePath: string,
	settings: BundleSettings,
	runner: BuildRunner = resolveBunBuildRunner(),
): Promise<void> {
	const { cwd, minify, envFiles, external } = settings;
	// Bun bundles an entry starting `#!/usr/bin/env bun` as Bun code even for `--target node`
	// (bundle_v2.rs target_from_hashbang, Bun 1.4.4); any other bun shebang is blanked too,
	// harmlessly, since the output gets its own. The output is marked `// @bun` and
	// `import.meta.main` lowers to a `__require` Node lacks. The driver blanks that line
	// as the entry loads, keeping its path, so back-imports and a symlinked entry's
	// relative imports resolve as before. Bun hands onLoad the real path.
	// TODO: Bun documents the shebang as replacing only the default target. Drop the blanking and
	// the `// @bun` check below once https://github.com/oven-sh/bun/issues/48810 is fixed.
	const stripShebang =
		target === "node" && /^#![^\n]*\bbun\b/.test(await readFile(entryPath, "utf8"))
			? [entryPath, await realpath(entryPath)]
			: undefined;
	if (settings.bunPlugins.length > 0 || stripShebang !== undefined) {
		await runBunPluginDriver(
			{
				entrypoints: [entryPath],
				minify,
				env: "PUBLIC_*",
				target,
				format: "esm",
				external,
			},
			outfilePath,
			settings,
			runner,
			stripShebang,
		);
	} else {
		await runBuildProcess(
			runner,
			[
				"build",
				...toBunEnvFileArgs(envFiles),
				"--env=PUBLIC_*",
				"--define",
				CRUST_BUILD_DEFINE_ARG,
				"--target",
				target,
				"--format",
				"esm",
				...external.flatMap((name) => ["--external", name]),
				"--outfile",
				outfilePath,
				...(minify ? ["--minify"] : []),
				entryPath,
			],
			outfilePath,
			cwd,
		);
	}

	const output = (await readFile(outfilePath, "utf8")).replace(/^#![^\n]*(?:\n|$)/, "");
	if (target === "node" && output.startsWith("// @bun")) {
		// Only a crust.bunPlugins onLoad that returns the entry itself gets here: it runs instead of the blanking one.
		throw new Error(
			`Build failed for ${outfilePath}: Bun emitted Bun-only code for a Node bundle because the entry reached it starting with "#!/usr/bin/env bun".\n  Remove that line from ${entryPath}, or from what a crust.bunPlugins onLoad hook returns for it.`,
		);
	}
	await writeFile(outfilePath, `#!/usr/bin/env ${target}\n${output}`);
	if (process.platform !== "win32") await chmod(outfilePath, 0o755);
}
