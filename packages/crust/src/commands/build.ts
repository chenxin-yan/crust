/**
 * The `crust build` command.
 *
 * Builds a CLI entry for Bun, Deno, or Node.
 * Bun and Deno produce standalone executables and multi-platform resolvers;
 * Node produces one executable JavaScript bundle.
 *
 * @example
 * ```sh
 * crust build                                 # Build for all platforms + resolver scripts
 * crust build --entry src/main.ts             # Custom entry point
 * crust build --name my-tool                  # Output as dist/my-tool-*
 * crust build --no-minify                     # Disable minification
 * crust build --target bun-linux-x64-baseline              # Build only for Linux x64
 * crust build --target bun-linux-x64-baseline --target bun-darwin-arm64  # Specific platforms only
 * crust build --target bun-linux-x64-baseline --outfile ./my-cli     # Single target with custom output
 * crust build --runtime deno --target aarch64-apple-darwin
 * crust build --runtime node --outdir out               # Output out/<name>.js
 * ```
 */
export const buildCommand = defineCommand(
	"build",
	{ description: "Build your CLI for Bun, Deno, or Node" },
	(command) =>
		command
			.flags(
				{
					name: "entry",
					type: "string",
					description: "Entry file path",
					default: "src/cli.ts",
					short: "e",
				},
				{
					name: "outfile",
					type: "string",
					description: "Output file path (single-target builds only)",
					short: "o",
				},
				{
					name: "name",
					type: "string",
					description: "Binary name (defaults to package.json name or entry filename)",
					short: "n",
				},
				{
					name: "minify",
					type: "boolean",
					// No default: deno builds must distinguish an explicit --minify (error)
					// from the implicit bun/node default (true, applied below).
					description: "Minify the output (default for bun and node; unsupported for deno)",
				},
				{
					name: "runtime",
					type: "string",
					choices: BUILD_RUNTIMES,
					description: "Build runtime (overrides package.json crust.runtime; defaults to bun)",
				},
				{
					name: "target",
					type: "string",
					multiple: true,
					description: "Canonical compiler target(s). Omit to build all platforms for Bun or Deno.",
					short: "t",
				},
				{
					name: "outdir",
					type: "string",
					description: "Output directory for build artifacts",
					default: "dist",
					short: "d",
				},
				{
					name: "resolver",
					type: "string",
					description: "Filename for the resolver script (multi-target builds, no extension)",
					default: "cli",
					short: "r",
				},
				{
					name: "validate",
					type: "boolean",
					description:
						"Materialize command definitions before compiling; --no-validate also skips Extension build hooks",
					default: true,
				},
				{
					name: "env-file",
					type: "string",
					multiple: true,
					description: "Explicit env file(s) used for build-time constants; repeatable",
				},
				{
					name: "package",
					type: "boolean",
					description: "Stage per-platform Bun npm packages in dist/npm",
					default: false,
				},
				{
					name: "stage-dir",
					type: "string",
					description: "Directory to stage npm packages into when using --package",
					default: "dist/npm",
				},
			)
			.action(async ({ flags, stdout, stderr }) => {
				const cwd = process.cwd();
				const io = { stdout, stderr };
				const plan = planBuild(flags, cwd);
				for (const warning of plan.warnings) stderr(warning);
				if (plan.validate) {
					await buildEntrypoint(plan.entryPath, plan.outDir, plan.envFiles, io, cwd);
				}

				if (plan.runtime === "bun" && plan.mode === "package") {
					await runDistributeBuild(plan, { io });
					return;
				}

				if (plan.runtime === "node") {
					stdout(`Building ${dim(plan.entryPath)} ${cyan("→")} ${dim(plan.outfilePath)}...`);
					await execNodeBuild(plan.entryPath, plan.outfilePath, plan.minify, plan.envFiles, cwd);
					stdout(`${green("✓")} Built successfully: ${plan.outfilePath}`);
					return;
				}

				if (plan.runtime === "bun") {
					await buildBinaryOutputs(
						plan,
						{
							execute: (entry, outfile, target, envFiles) =>
								execBuild(entry, outfile, plan.minify, target, envFiles, cwd),
							writeResolver: (path, baseName, targets) =>
								writeResolver(BUN_TARGETS, path, baseName, targets),
						},
						io,
					);
					return;
				}
				await buildBinaryOutputs(
					plan,
					{
						execute: (entry, outfile, target) => execDenoBuild(entry, outfile, target, cwd),
						writeResolver: (path, baseName, targets) =>
							writeResolver(DENO_TARGETS, path, baseName, targets),
					},
					io,
				);
			}),
);
